/**
 * Resolves the appropriate title-matching photo URL for any product.
 */
export function resolveProductImage(name: string, currentImage?: string | null, category?: string): string {
  if (
    currentImage &&
    !currentImage.includes("placeholder") &&
    currentImage.trim() !== ""
  ) {
    return currentImage
  }

  const cleanName = (name || "").trim()

  // 1. Direct exact match
  if (PRODUCT_IMAGE_MAP[cleanName]) {
    return PRODUCT_IMAGE_MAP[cleanName]
  }

  // 2. Case-insensitive match
  const lowerName = cleanName.toLowerCase()
  for (const [key, url] of Object.entries(PRODUCT_IMAGE_MAP)) {
    if (key.toLowerCase() === lowerName) {
      return url
    }
  }

  // 3. Keyword / partial matching
  if (lowerName.includes("scone") || lowerName.includes("slice") || lowerName.includes("muffin")) return "https://images.unsplash.com/photo-1509440159596-0249088772ff?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("quiche")) return "https://images.unsplash.com/photo-1550547660-d9450f859349?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("sandwich")) return "https://images.unsplash.com/photo-1528735602780-2552fd46c7af?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("salad")) return "/vibrant-mixed-salad.png"
  if (lowerName.includes("pancake")) return "https://images.unsplash.com/photo-1567620905732-2d1ec7ab7445?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("egg") || lowerName.includes("scramble")) return "https://images.unsplash.com/photo-1525351484163-7529414344d8?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("mushroom")) return "https://images.unsplash.com/photo-1546069901-ba9599a7e63c?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("brownie") || lowerName.includes("chocolate")) return "/chocolate-brownie.png"
  if (lowerName.includes("matcha")) return "https://images.unsplash.com/photo-1536256263959-770b48d82b0a?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("shake") || lowerName.includes("smoothie")) return "https://images.unsplash.com/photo-1553530666-ba11a7da3888?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("soda") || lowerName.includes("sozo") || lowerName.includes("lemonade")) return "https://images.unsplash.com/photo-1513558161293-cdaf765ed2fd?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("coconut")) return "https://images.unsplash.com/photo-1525385133512-2f3bdd039054?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("tea")) return "https://images.unsplash.com/photo-1576092768241-dec231879fc3?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("ristretto")) return "/uploads/prod_1794637814975_5gmi8.jpg"
  if (lowerName.includes("latte") || lowerName.includes("cappuccino") || lowerName.includes("flat white")) return "/latte-coffee.png"
  if (lowerName.includes("espresso") || lowerName.includes("pour over") || lowerName.includes("black")) return "https://images.unsplash.com/photo-1510591509098-f4fdc6d0ff04?auto=format&fit=crop&w=600&q=80"
  if (lowerName.includes("water")) return "/bottled-water.png"

  // 4. Category-based fallback
  const cat = (category || "").toLowerCase()
  if (cat.includes("coffee")) return "/latte-coffee.png"
  if (cat.includes("tea")) return "https://images.unsplash.com/photo-1576092768241-dec231879fc3?auto=format&fit=crop&w=600&q=80"
  if (cat.includes("smoothie") || cat.includes("shake")) return "https://images.unsplash.com/photo-1553530666-ba11a7da3888?auto=format&fit=crop&w=600&q=80"
  if (cat.includes("drink") || cat.includes("soda")) return "https://images.unsplash.com/photo-1513558161293-cdaf765ed2fd?auto=format&fit=crop&w=600&q=80"
  if (cat.includes("bakery") || cat.includes("dessert")) return "https://images.unsplash.com/photo-1509440159596-0249088772ff?auto=format&fit=crop&w=600&q=80"
  if (cat.includes("sandwich") || cat.includes("quiche")) return "https://images.unsplash.com/photo-1528735602780-2552fd46c7af?auto=format&fit=crop&w=600&q=80"
  if (cat.includes("salad")) return "/vibrant-mixed-salad.png"
  if (cat.includes("breakfast")) return "https://images.unsplash.com/photo-1525351484163-7529414344d8?auto=format&fit=crop&w=600&q=80"

  return "/placeholder.svg"
}
